"""Import the pinned, unmodified upstream neural network implementation."""

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODEL_PATH = ROOT / "upstream/FedGCDR/model/fedgcdr/model.py"
UPSTREAM_COMMIT = "09c63ef5b36903dfbadee86b31aabdcee7f98205"


def load_upstream():
    if not MODEL_PATH.is_file():
        raise FileNotFoundError(f"Restore the pinned upstream checkout: {MODEL_PATH}")
    spec = importlib.util.spec_from_file_location("fedgcdr_original_model", MODEL_PATH)
    module = importlib.util.module_from_spec(spec)
    previous = sys.dont_write_bytecode
    try:
        # Keep even generated bytecode outside the preserved upstream worktree.
        sys.dont_write_bytecode = True
        spec.loader.exec_module(module)
    finally:
        sys.dont_write_bytecode = previous
    return module


_model = load_upstream()
GAT = _model.GAT
MLP = _model.MLP
